/**
 * Renders the standard report header with logo, company name, and report metadata.
 * @param {PDFDocument} doc
 * @param {{ reportType: string, startDate?: string, endDate?: string, generatedBy?: string, lang?: string }} opts
 */
export function renderHeader(doc, opts = {}) {
  const s = getStrings(opts.lang || 'en');
  const reportTitle = s[opts.reportType] || opts.reportType || s.report;
  const pageWidth = doc.page.width - doc.page.margins.left - doc.page.margins.right;

  // Brand bar at the top
  doc.save();
  doc.rect(0, 0, doc.page.width, 8).fill(BRAND.primary);
  doc.rect(0, 8, doc.page.width, 3).fill(BRAND.accent);
  doc.restore();

  let yPos = 25;

  // Logo
  if (fs.existsSync(LOGO_PATH)) {
    doc.image(LOGO_PATH, doc.page.margins.left, yPos, { width: 45 });
  }

  // Company name and tagline
  doc.fontSize(18).fillColor(BRAND.primary)
    .text(s.companyName, doc.page.margins.left + 55, yPos + 4, { width: pageWidth - 55 });
  doc.fontSize(9).fillColor(BRAND.textMuted)
    .text(s.companyTagline, doc.page.margins.left + 55, yPos + 24, { width: pageWidth - 55 });

  yPos += 50;

  // Horizontal divider
  doc.moveTo(doc.page.margins.left, yPos).lineTo(doc.page.width - doc.page.margins.right, yPos)
    .strokeColor(BRAND.tableBorder).lineWidth(0.5).stroke();

  yPos += 12;

  // Report title
  doc.fontSize(14).fillColor(BRAND.textDark)
    .text(reportTitle, doc.page.margins.left, yPos, { width: pageWidth });
  yPos += 22;

  // Metadata line: period + generation time
  const periodStr = (opts.startDate && opts.endDate)
    ? `${fmtDate(opts.startDate)} — ${fmtDate(opts.endDate)}`
    : s.allTime;
  doc.fontSize(9).fillColor(BRAND.textMuted)
    .text(`${s.period}: ${periodStr}`, doc.page.margins.left, yPos, { width: pageWidth / 2, continued: false });

  doc.fontSize(9).fillColor(BRAND.textMuted)
    .text(`${s.generated}: ${fmtDateTime(new Date())}`, doc.page.margins.left + pageWidth / 2, yPos, {
      width: pageWidth / 2, align: 'right',
    });

  yPos += 14;

  if (opts.generatedBy) {
    doc.fontSize(9).fillColor(BRAND.textMuted)
      .text(`${s.generatedBy}: ${opts.generatedBy}`, doc.page.margins.left, yPos, { width: pageWidth });
    yPos += 14;
  }

  // Bottom divider
  doc.moveTo(doc.page.margins.left, yPos).lineTo(doc.page.width - doc.page.margins.right, yPos)
    .strokeColor(BRAND.tableBorder).lineWidth(0.5).stroke();

  doc.y = yPos + 16;
}

/**
 * Renders the page footer with company name, page number, and confidentiality notice.
 * Must be called AFTER all content is added and before doc.end().
 * Uses bufferPages to add page numbers.
 * @param {PDFDocument} doc
 * @param {{ lang?: string }} opts
 */
export function renderFooters(doc, opts = {}) {
  const s = getStrings(opts.lang || 'en');
  const pageCount = doc.bufferedPageRange().count;

  for (let i = 0; i < pageCount; i++) {
    doc.switchToPage(i);

    const footerY = doc.page.height - 45;
    const pageWidth = doc.page.width - doc.page.margins.left - doc.page.margins.right;

    // Top divider line
    doc.save();
    doc.moveTo(doc.page.margins.left, footerY)
      .lineTo(doc.page.width - doc.page.margins.right, footerY)
      .strokeColor(BRAND.tableBorder).lineWidth(0.5).stroke();

    // Copyright
    doc.fontSize(7).fillColor(BRAND.textMuted)
      .text(s.copyright, doc.page.margins.left, footerY + 6, { width: pageWidth / 2 });

    // Page number
    doc.fontSize(7).fillColor(BRAND.textMuted)
      .text(`${s.page} ${i + 1} ${s.of} ${pageCount}`, doc.page.margins.left, footerY + 6, {
        width: pageWidth, align: 'center',
      });

    // Confidential notice
    doc.fontSize(7).fillColor(BRAND.textMuted)
      .text(s.confidential, doc.page.margins.left, footerY + 6, {
        width: pageWidth, align: 'right',
      });

    doc.restore();
  }
}

/**
 * Renders a section title with a left accent bar.
 * @param {PDFDocument} doc
 * @param {string} title
 * @param {{ color?: string }} opts
 */
export function renderSectionTitle(doc, title, opts = {}) {
  const color = opts.color || BRAND.primary;
  const y = doc.y;

  // Accent bar
  doc.rect(doc.page.margins.left, y, 3, 16).fill(color);
  doc.fontSize(11).fillColor(BRAND.textDark)
    .text(title, doc.page.margins.left + 10, y + 2);
  doc.y = y + 24;
}

/**
 * Renders a KPI summary grid (up to 4 metrics per row).
 * @param {PDFDocument} doc
 * @param {Array<{ label: string, value: string|number, sub?: string }>} metrics
 */
export function renderKpiSummary(doc, metrics) {
  const pageWidth = doc.page.width - doc.page.margins.left - doc.page.margins.right;
  const colCount = Math.min(metrics.length, 4);
  const colWidth = pageWidth / colCount;
  const startY = doc.y;
  const boxHeight = 52;

  for (let i = 0; i < metrics.length; i++) {
    const col = i % colCount;
    const row = Math.floor(i / colCount);
    const x = doc.page.margins.left + col * colWidth;
    const y = startY + row * (boxHeight + 8);

    // Background box
    doc.save();
    doc.roundedRect(x + 2, y, colWidth - 4, boxHeight, 4).fill('#F9FAFB');

    // Value
    doc.fontSize(18).fillColor(BRAND.primary)
      .text(String(metrics[i].value), x + 10, y + 8, { width: colWidth - 20 });

    // Label
    doc.fontSize(8).fillColor(BRAND.textMuted)
      .text(metrics[i].label, x + 10, y + 30, { width: colWidth - 20 });

    // Subtitle
    if (metrics[i].sub) {
      doc.fontSize(7).fillColor(BRAND.textMuted)
        .text(metrics[i].sub, x + 10, y + 40, { width: colWidth - 20 });
    }

    doc.restore();
  }

  const totalRows = Math.ceil(metrics.length / colCount);
  doc.y = startY + totalRows * (boxHeight + 8) + 8;
}

/**
 * Renders a data table with headers and rows.
 * Handles pagination automatically when content overflows the page.
 * @param {PDFDocument} doc
 * @param {{ headers: Array<{ label: string, width: number, align?: string }>, rows: Array<Array<string>> }} tableData
 */
export function renderTable(doc, tableData) {
  const { headers, rows } = tableData;
  const pageWidth = doc.page.width - doc.page.margins.left - doc.page.margins.right;

  // Calculate column widths as proportions
  const totalWidthUnits = headers.reduce((sum, h) => sum + h.width, 0);
  const colWidths = headers.map(h => (h.width / totalWidthUnits) * pageWidth);

  const rowHeight = 20;
  const headerHeight = 24;
  const maxY = doc.page.height - doc.page.margins.bottom - 50; // Leave room for footer

  function drawHeaderRow() {
    const y = doc.y;
    let x = doc.page.margins.left;

    // Header background
    doc.save();
    doc.rect(x, y, pageWidth, headerHeight).fill(BRAND.tableHeaderBg);

    for (let i = 0; i < headers.length; i++) {
      doc.fontSize(8).fillColor(BRAND.white)
        .text(headers[i].label, x + 4, y + 6, {
          width: colWidths[i] - 8,
          align: headers[i].align || 'left',
          lineBreak: false,
        });
      x += colWidths[i];
    }

    doc.restore();
    doc.y = y + headerHeight;
  }

  function drawDataRow(rowData, rowIndex) {
    const y = doc.y;

    // Check if we need a new page
    if (y + rowHeight > maxY) {
      doc.addPage();
      doc.y = doc.page.margins.top + 10;
      drawHeaderRow();
    }

    const currentY = doc.y;
    let x = doc.page.margins.left;

    // Zebra striping
    if (rowIndex % 2 === 1) {
      doc.save();
      doc.rect(x, currentY, pageWidth, rowHeight).fill(BRAND.tableRowAlt);
      doc.restore();
    }

    // Row border
    doc.save();
    doc.moveTo(x, currentY + rowHeight)
      .lineTo(x + pageWidth, currentY + rowHeight)
      .strokeColor(BRAND.tableBorder).lineWidth(0.3).stroke();
    doc.restore();

    for (let i = 0; i < headers.length; i++) {
      const cellValue = (rowData[i] != null) ? String(rowData[i]) : '';
      doc.fontSize(8).fillColor(BRAND.textDark)
        .text(cellValue, x + 4, currentY + 5, {
          width: colWidths[i] - 8,
          align: headers[i].align || 'left',
          lineBreak: false,
        });
      x += colWidths[i];
    }

    doc.y = currentY + rowHeight;
  }

  // Draw the table
  drawHeaderRow();
  rows.forEach((row, idx) => drawDataRow(row, idx));

  doc.y += 12;
}

/**
 * Renders a "no data" message when the report has no records.
 * @param {PDFDocument} doc
 * @param {{ lang?: string }} opts
 */
export function renderNoData(doc, opts = {}) {
  const s = getStrings(opts.lang || 'en');
  const pageWidth = doc.page.width - doc.page.margins.left - doc.page.margins.right;

  doc.y += 30;
  doc.save();
  doc.roundedRect(doc.page.margins.left, doc.y, pageWidth, 40, 4)
    .fillAndStroke('#FEF3C7', '#F59E0B');
  doc.fontSize(10).fillColor(BRAND.textDark)
    .text(s.noData, doc.page.margins.left + 12, doc.y + 13, { width: pageWidth - 24, align: 'center' });
  doc.restore();
  doc.y += 52;
}

