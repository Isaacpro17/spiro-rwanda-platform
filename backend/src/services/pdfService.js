/**
 * Resolves the language strings to use for the PDF.
 * @param {'en'|'rw'} lang
 * @returns {Object}
 */
function getStrings(lang) {
  return PDF_STRINGS[lang] || PDF_STRINGS.en;
}

/**
 * Formats a date to a human-readable string for PDF display.
 * @param {Date|string} d
 * @returns {string}
 */
function fmtDate(d) {
  if (!d) return 'N/A';
  const date = d instanceof Date ? d : new Date(d);
  return date.toLocaleDateString('en-GB', {
    day: '2-digit', month: 'short', year: 'numeric',
  });
}

/**
 * Formats a datetime with time.
 * @param {Date|string} d
 * @returns {string}
 */
function fmtDateTime(d) {
  if (!d) return 'N/A';
  const date = d instanceof Date ? d : new Date(d);
  return date.toLocaleDateString('en-GB', {
    day: '2-digit', month: 'short', year: 'numeric',
    hour: '2-digit', minute: '2-digit', timeZone: 'Africa/Kigali',
  });
}

/**
 * Formats a number as RWF currency.
 * @param {number} n
 * @returns {string}
 */
function fmtRwf(n) {
  if (n == null || isNaN(n)) return 'RWF 0';
  return `RWF ${Number(n).toLocaleString('en-US')}`;
}

/**
 * Shortens large numbers for summary cards.
 * @param {number} n
 * @returns {string}
 */
function fmtCompact(n) {
  if (n >= 1_000_000) return `${(n / 1_000_000).toFixed(1)}M`;
  if (n >= 1_000) return `${(n / 1_000).toFixed(1)}K`;
  return String(n);
}

