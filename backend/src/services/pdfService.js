/**
 * Renders the Swap Operations Summary report.
 * @param {PDFDocument} doc
 * @param {Object} data - { kpis, swaps }
 * @param {Object} opts - { lang, startDate, endDate, generatedBy }
 */
export function renderSwapOperationsPdf(doc, data, opts = {}) {
  const s = getStrings(opts.lang || 'en');

  renderHeader(doc, { reportType: 'swap_operations', ...opts });

  // KPI Summary
  renderSectionTitle(doc, s.summary);
  renderKpiSummary(doc, [
    { label: 'Total Swaps', value: fmtCompact(data.kpis?.totalSwaps || 0) },
    { label: 'Completed', value: fmtCompact(data.kpis?.completedSwaps || 0) },
    { label: 'Avg Wait Time', value: `${data.kpis?.avgWaitTimeMinutes || 0} min` },
    { label: 'Total Revenue', value: fmtRwf(data.kpis?.totalRevenueRwf || 0) },
  ]);

  // Detailed swap table
  if (data.swaps && data.swaps.length > 0) {
    renderSectionTitle(doc, s.details);
    renderTable(doc, {
      headers: [
        { label: '#', width: 1, align: 'center' },
        { label: 'Date', width: 3 },
        { label: 'Station', width: 3 },
        { label: 'Rider', width: 3 },
        { label: 'Duration', width: 2, align: 'center' },
        { label: 'Amount (RWF)', width: 3, align: 'right' },
        { label: 'Status', width: 2, align: 'center' },
      ],
      rows: data.swaps.map((sw, i) => [
        String(i + 1),
        fmtDate(sw.createdAt || sw.startTime),
        sw.stationId?.name || sw.stationName || 'N/A',
        sw.riderId?.fullName || sw.riderName || 'N/A',
        sw.durationMinutes ? `${sw.durationMinutes} min` : 'N/A',
        sw.amountRwf != null ? Number(sw.amountRwf).toLocaleString() : 'N/A',
        sw.status || 'N/A',
      ]),
    });
  } else {
    renderNoData(doc, opts);
  }
}

/**
 * Renders the Financial/Revenue Report.
 * @param {PDFDocument} doc
 * @param {Object} data - { stats, payments }
 * @param {Object} opts
 */
export function renderFinancialPdf(doc, data, opts = {}) {
  const s = getStrings(opts.lang || 'en');

  renderHeader(doc, { reportType: 'financial', ...opts });

  // KPI Summary
  renderSectionTitle(doc, s.summary);
  renderKpiSummary(doc, [
    { label: 'Total Revenue', value: fmtRwf(data.stats?.totalRevenue || 0) },
    { label: 'Today Revenue', value: fmtRwf(data.stats?.todayRevenue || 0) },
    { label: 'Total Transactions', value: fmtCompact(data.stats?.total || 0) },
    { label: 'Today Transactions', value: String(data.stats?.todayTransactions || 0) },
  ]);

  // Provider breakdown
  if (data.stats?.byProvider) {
    doc.y += 4;
    doc.fontSize(9).fillColor(BRAND.textDark)
      .text('Revenue by Provider:', doc.page.margins.left, doc.y);
    doc.y += 14;
    const providers = Object.entries(data.stats.byProvider);
    for (const [provider, count] of providers) {
      doc.fontSize(8).fillColor(BRAND.textMuted)
        .text(`  • ${provider.replace('_', ' ').toUpperCase()}: ${count} transactions`, doc.page.margins.left, doc.y);
      doc.y += 12;
    }
    doc.y += 6;
  }

  // Payments table
  if (data.payments && data.payments.length > 0) {
    renderSectionTitle(doc, s.details);
    renderTable(doc, {
      headers: [
        { label: '#', width: 1, align: 'center' },
        { label: 'Transaction ID', width: 3 },
        { label: 'Date', width: 3 },
        { label: 'Rider', width: 3 },
        { label: 'Provider', width: 2 },
        { label: 'Type', width: 2 },
        { label: 'Amount (RWF)', width: 3, align: 'right' },
        { label: 'Status', width: 2, align: 'center' },
      ],
      rows: data.payments.map((p, i) => [
        String(i + 1),
        p.transactionId || 'N/A',
        fmtDate(p.createdAt),
        p.riderId?.fullName || 'N/A',
        (p.provider || '').replace('_', ' '),
        (p.type || '').replace('_', ' '),
        Number(p.amountRwf || 0).toLocaleString(),
        p.refunded ? 'Refunded' : (p.status || 'N/A'),
      ]),
    });
  } else {
    renderNoData(doc, opts);
  }
}

