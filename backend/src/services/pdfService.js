/**
 * Creates a new PDFKit document with standard A4 settings and margins.
 * @returns {PDFDocument}
 */
export function createBaseDocument() {
  const doc = new PDFDocument({
    size: 'A4',
    margins: { top: 60, bottom: 60, left: 50, right: 50 },
    info: {
      Title: 'Spiro Rwanda Report',
      Author: 'Spiro Rwanda Platform',
      Creator: 'Spiro Rwanda Platform',
    },
    bufferPages: true, // Enable page buffering for page count in footer
  });

  return doc;
}

